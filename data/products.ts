const img = (query: string) =>
  `https://loremflickr.com/800/800/${encodeURIComponent(query)},food/all`;

const makeSlug = (name: string, id: number) =>
  `${name
    .toLowerCase()
    .replace(/[^a-z0-9\u0600-\u06ff]+/g, "-")
    .replace(/^-+|-+$/g, "")}-${id}`;

